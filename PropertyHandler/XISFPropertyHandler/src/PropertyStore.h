struct PropertyEntry {
    PROPERTYKEY key;
    PROPVARIANT value;

    PropertyEntry() : key{}, value{} { PropVariantInit(&value); }
    ~PropertyEntry() { PropVariantClear(&value); }

    PropertyEntry(PropertyEntry&& other) noexcept : key(other.key), value(other.value) {
        PropVariantInit(&other.value);
    }
    PropertyEntry& operator=(PropertyEntry&& other) noexcept {
        if (this != &other) {
            PropVariantClear(&value);
            key = other.key;
            value = other.value;
            PropVariantInit(&other.value);
        }
        return *this;
    }
    PropertyEntry(const PropertyEntry&) = delete;
    PropertyEntry& operator=(const PropertyEntry&) = delete;
};

